/** Embaralha uma cópia do array (Fisher-Yates). */
export function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** Filtra o banco por matérias e dificuldade. */
export function poolDeQuestoes(materias, dificuldade = 'todas') {
  return QUESTOES.filter(
    (q) =>
      materias.includes(q.materia) &&
      (dificuldade === 'todas' || q.dificuldade === dificuldade),
  )
}

/**
 * Critério de aceite: sorteia EXATAMENTE 10 questões aleatórias
 * a partir das matérias selecionadas.
 */
export const QUESTOES_POR_TREINO = 10

export function sortearTreino(materias, dificuldade = 'todas', total = QUESTOES_POR_TREINO) {
  const pool = poolDeQuestoes(materias, dificuldade)
  if (pool.length < total) return null // pool insuficiente
  return shuffle(pool)
    .slice(0, total)
    .map((q) => ({ ...q, alternativas: [...q.alternativas] }))
}

export function contarDisponiveis(materias, dificuldade = 'todas') {
  return poolDeQuestoes(materias, dificuldade).length
}
